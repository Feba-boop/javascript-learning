function dodawanie(a, b) {
    return a + b;
}
function odejmowanie(a, b) {
    return a - b;
}
function mnożenie(a, b) {
    return a * b;
}

let wynikDodawania = dodawanie(10, 5);
let wynikOdejmowania = odejmowanie(16, 5);
let wynikMnożenia = mnożenie(18, 7);

console.log("Wynik dodawania: " + wynikDodawania);
console.log("Wynik odejmowania: " + wynikOdejmowania);
console.log("Wynik mnożenia: " + wynikMnożenia);